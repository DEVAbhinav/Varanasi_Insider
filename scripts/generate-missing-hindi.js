function toHindiBasic(str) {
  if (!str) return str;
  let out = str;
  map.forEach(([en, hi]) => {
    out = out.replace(new RegExp(en, 'gi'), match => {
      // Preserve case first letter maybe
      return hi;
    });
  });
  return out;
}

function ensureDir(filePath) {
  const dir = path.dirname(filePath);
  fs.mkdirSync(dir, { recursive: true });
}

function parseFrontMatter(raw) {
  if (!raw.startsWith('---')) return { fm: {}, body: raw };
  const parts = raw.split(/\n---\n/);
  if (parts.length < 2) return { fm: {}, body: raw };
  const fmBlock = parts[0].replace(/^---\n?/, '');
  const body = parts.slice(1).join('\n---\n');
  const fm = {};
  fmBlock.split(/\n/).forEach(line => {
    if (!line.trim() || line.trim().startsWith('#')) return;
    const idx = line.indexOf(':');
    if (idx === -1) return;
    const key = line.slice(0, idx).trim();
    let val = line.slice(idx + 1).trim();
    fm[key] = val.replace(/^"|"$/g, '');
  });
  return { fm, body };
}

function buildHindiFrontMatter(fm, relPath) {
  const originalTitle = fm.title || '';
  const hiTitle = toHindiBasic(originalTitle)
    .replace(/\s+\[2025\]/, ' 2025')
    .replace(/\s+\[2026\]/, ' 2026');
  const originalDesc = fm.description || fm.metaDescription || '';
  const hiDesc = toHindiBasic(originalDesc);
  const slug = (fm.slug || relPath.replace(/\.md$/, ''));
  const canonical = (fm.canonical || '').replace('/en/', '/hi/');
  const metaTitle = fm.metaTitle ? toHindiBasic(fm.metaTitle) : hiTitle;
  const metaDescription = hiDesc;

  return `---\nlang: hi\nsourceSlug: ${slug}\ntitle: "${hiTitle}"\nslug: "${slug}"\noriginalEnglishTitle: "${originalTitle.replace(/"/g,'\"')}"\ndescription: "${hiDesc.replace(/"/g,'\"')}"\nmetaTitle: "${metaTitle.replace(/"/g,'\"')}"\nmetaDescription: "${metaDescription.replace(/"/g,'\"')}"\ncanonical: "${canonical}"\nautoGenerated: true\ntranslationStatus: draft\n---\n`;
}

function extractKeyPoints(body) {
  const lines = body.split(/\n/);
  const bullets = [];
  for (const ln of lines) {
    if (bullets.length >= 12) break;
    if (/^[-*]\s+/.test(ln) && ln.length < 160) {
      bullets.push(ln.replace(/^[-*]\s+/, ''));
    }
  }
  return bullets;
}

function translateBullet(b) {
  return toHindiBasic(b)
    .replace(/\bINR\b/g, '₹')
    .replace(/Rs?\.?/gi, '₹');
}

